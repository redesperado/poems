/**
 * 获取全量风物字典 (按 ID 索引)
 */
export const ALL_ARTIFACTS: Record<string, ArtifactItem> = (() => {
  const result: Record<string, ArtifactItem> = {};

  // 1. 文人专属本命信物
  Object.values(POET_EXCLUSIVE_ARTIFACTS).forEach((list) => {
    list.forEach((art) => {
      result[art.id] = art;
    });
  });

  // 2. 名城特产风物
  Object.values(CITY_HERITAGE_ARTIFACTS).forEach((art) => {
    result[art.id] = art;
  });

  return result;
})();

/**
 * 根据城市 ID 查找该城市的特色风物 (若是，则返回)
 */
export function getCityArtifact(cityId: string): ArtifactItem | null {
  // 映射常见的别名 ID
  const normalizedId = cityId === 'jingxian' ? 'jiankang' : cityId === 'huanghelou' ? 'wuhan' : cityId === 'xunyang' ? 'jiujiang' : cityId;
  return CITY_HERITAGE_ARTIFACTS[normalizedId] || null;
}

/**
 * 获取某个诗人的专属本命信物列表
 */
export function getPoetExclusiveArtifacts(poetId: string): ArtifactItem[] {
  return POET_EXCLUSIVE_ARTIFACTS[poetId] || [];
}
